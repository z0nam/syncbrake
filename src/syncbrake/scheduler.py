"""Zero-polling scheduled pause & conditional auto-resume (launchd on macOS, systemd on Linux)."""

from __future__ import annotations

import os
import platform
import re
import subprocess
from datetime import datetime, time as dtime, timedelta
from pathlib import Path
from typing import Any


PLIST_LABEL = "com.namun.gdrive-resume"
PLIST_PATH = Path.home() / "Library" / "LaunchAgents" / f"{PLIST_LABEL}.plist"
SCRIPT_PATH = Path.home() / ".local" / "bin" / "gdrive-auto-resume"
LOG_PATH = Path("/tmp/gdrive-auto-resume.log")
FLAG_PATH = Path("/tmp/gdrive-paused-16-24.flag")


def parse_hhmm_to_epoch(hhmm: str, base_dt: datetime | None = None, must_be_after: int | None = None) -> tuple[int, str]:
    now = base_dt or datetime.now()
    if hhmm in ("24:00", "00:00", "midnight"):
        target_dt = datetime.combine(now.date() + timedelta(days=1), dtime(0, 0, 0))
    elif hhmm.endswith("h") and hhmm[:-1].isdigit():
        hours = int(hhmm[:-1])
        target_dt = now + timedelta(hours=hours)
    elif hhmm.endswith("m") and hhmm[:-1].isdigit():
        mins = int(hhmm[:-1])
        target_dt = now + timedelta(minutes=mins)
    else:
        parts = hhmm.split(":")
        h, m = int(parts[0]), int(parts[1]) if len(parts) > 1 else 0
        target_dt = datetime.combine(now.date(), dtime(h, m, 0))
        if must_be_after is not None and int(target_dt.timestamp()) <= must_be_after:
            target_dt += timedelta(days=1)
    return int(target_dt.timestamp()), target_dt.strftime("%Y-%m-%d %H:%M:%S")


def get_schedule_status() -> dict[str, Any]:
    if not PLIST_PATH.exists() or not SCRIPT_PATH.exists():
        return {"active": False}

    text = SCRIPT_PATH.read_text(encoding="utf-8", errors="ignore")
    pause_m = re.search(r"PAUSE_START_EPOCH=(\d+)", text)
    resume_m = re.search(r"RESUME_START_EPOCH=(\d+)", text)
    target_m = re.search(r'TARGET_EPOCH="\$\{1:-(\d+)\}"', text)

    pause_epoch = int(pause_m.group(1)) if pause_m else None
    resume_epoch = int(resume_m.group(1)) if resume_m else (int(target_m.group(1)) if target_m else None)

    def _fmt(ep: int | None) -> str:
        return datetime.fromtimestamp(ep).strftime("%Y-%m-%d %H:%M:%S") if ep else ""

    return {
        "active": True,
        "label": PLIST_LABEL,
        "plist": str(PLIST_PATH),
        "script": str(SCRIPT_PATH),
        "pause_from_epoch": pause_epoch,
        "pause_from_str": _fmt(pause_epoch),
        "resume_after_epoch": resume_epoch,
        "resume_after_str": _fmt(resume_epoch),
        "when_online": "curl" in text and "google.com" in text,
        "log_file": str(LOG_PATH),
    }


def schedule_window_or_until(
    from_hhmm: str | None = None,
    until_hhmm: str = "24:00",
    when_online: bool = True,
) -> dict[str, Any]:
    now = datetime.now()
    if from_hhmm:
        pause_epoch, pause_str = parse_hhmm_to_epoch(from_hhmm, now)
    else:
        pause_epoch, pause_str = int(now.timestamp()), now.strftime("%Y-%m-%d %H:%M:%S")

    resume_epoch, resume_str = parse_hhmm_to_epoch(until_hhmm, now, must_be_after=pause_epoch)
    pause_dt = datetime.fromtimestamp(pause_epoch)
    resume_dt = datetime.fromtimestamp(resume_epoch)

    SCRIPT_PATH.parent.mkdir(parents=True, exist_ok=True)
    PLIST_PATH.parent.mkdir(parents=True, exist_ok=True)

    online_check = """
if ! /usr/bin/curl -sI --max-time 5 "https://www.google.com" >/dev/null 2>&1; then
    echo "[$(date '+%Y-%m-%d %H:%M:%S')] Past resume time, but offline. Waiting for connection..." >> "$LOG_FILE"
    exit 0
fi
""" if when_online else ""

    script_content = f"""#!/bin/sh
# Generated by SyncBrake (sb)
PAUSE_START_EPOCH={pause_epoch}  # {pause_str}
RESUME_START_EPOCH={resume_epoch} # {resume_str}
NOW_EPOCH="$(date +%s)"

LOG_FILE="{LOG_PATH}"
PAUSE_FLAG="{FLAG_PATH}"
GDRIVE_BIN="/Applications/Google Drive.app/Contents/MacOS/Google Drive"
PLIST_PATH="{PLIST_PATH}"

if [ "$NOW_EPOCH" -lt "$PAUSE_START_EPOCH" ]; then
    exit 0
fi

if [ "$NOW_EPOCH" -ge "$PAUSE_START_EPOCH" ] && [ "$NOW_EPOCH" -lt "$RESUME_START_EPOCH" ]; then
    if /usr/bin/pgrep -x "Resilio Sync" >/dev/null 2>&1; then
        /usr/bin/killall "Resilio Sync" >/dev/null 2>&1 || true
        echo "[$(date '+%Y-%m-%d %H:%M:%S')] [Pause Window] Stopped Resilio Sync." >> "$LOG_FILE"
    fi
    if [ ! -f "$PAUSE_FLAG" ]; then
        if /usr/bin/pgrep -x "Google Drive" >/dev/null 2>&1; then
            OUTPUT="$("$GDRIVE_BIN" --pause_syncing 2>&1)"
            if echo "$OUTPUT" | /usr/bin/grep -q "Remote control request returned status: OK"; then
                /usr/bin/touch "$PAUSE_FLAG"
                echo "[$(date '+%Y-%m-%d %H:%M:%S')] [Pause Window] Paused Google Drive syncing." >> "$LOG_FILE"
                /usr/bin/osascript -e 'display notification "예약된 배터리 절약 구간에 진입하여 Google Drive와 Resilio Sync를 일시정지했습니다." with title "SyncBrake 자동 일시정지"' >/dev/null 2>&1 || true
            fi
        else
            /usr/bin/touch "$PAUSE_FLAG"
        fi
    fi
    exit 0
fi
{online_check}
if ! /usr/bin/pgrep -x "Resilio Sync" >/dev/null 2>&1; then
    /usr/bin/open -g -a "Resilio Sync"
fi
if ! /usr/bin/pgrep -x "Google Drive" >/dev/null 2>&1; then
    /usr/bin/open -g -a "Google Drive"
    /bin/sleep 8
fi

OUTPUT="$("$GDRIVE_BIN" --resume_syncing 2>&1)"
if echo "$OUTPUT" | /usr/bin/grep -q "Remote control request returned status: OK"; then
    echo "[$(date '+%Y-%m-%d %H:%M:%S')] Successfully resumed Google Drive & Resilio Sync." >> "$LOG_FILE"
    /usr/bin/osascript -e 'display notification "예약 시각 이후 조건이 충족되어 Google Drive와 Resilio Sync 동기화를 재개했습니다." with title "SyncBrake 자동 재개"' >/dev/null 2>&1 || true
    rm -f "$PAUSE_FLAG" "$PLIST_PATH"
    /bin/launchctl bootout "gui/$(/usr/bin/id -u)/{PLIST_LABEL}" >/dev/null 2>&1 || true
    exit 0
fi
exit 1
"""
    SCRIPT_PATH.write_text(script_content, encoding="utf-8")
    SCRIPT_PATH.chmod(0o755)

    plist_content = f"""<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
    <key>Label</key>
    <string>{PLIST_LABEL}</string>
    <key>ProgramArguments</key>
    <array>
        <string>{SCRIPT_PATH}</string>
    </array>
    <key>StartCalendarInterval</key>
    <array>
        <dict>
            <key>Hour</key>
            <integer>{pause_dt.hour}</integer>
            <key>Minute</key>
            <integer>{pause_dt.minute}</integer>
        </dict>
        <dict>
            <key>Hour</key>
            <integer>{resume_dt.hour}</integer>
            <key>Minute</key>
            <integer>{resume_dt.minute}</integer>
        </dict>
    </array>
    <key>StartInterval</key>
    <integer>300</integer>
    <key>WatchPaths</key>
    <array>
        <string>/Library/Preferences/SystemConfiguration</string>
    </array>
    <key>StandardOutPath</key>
    <string>{LOG_PATH}</string>
    <key>StandardErrorPath</key>
    <string>{LOG_PATH}</string>
</dict>
</plist>
"""
    PLIST_PATH.write_text(plist_content, encoding="utf-8")
    if FLAG_PATH.exists():
        FLAG_PATH.unlink()

    if platform.system().lower() == "darwin":
        uid = os.getuid()
        subprocess.run(["launchctl", "bootout", f"gui/{uid}/{PLIST_LABEL}"], capture_output=True)
        subprocess.run(["launchctl", "bootstrap", f"gui/{uid}", str(PLIST_PATH)], capture_output=True)
        # Trigger once immediately in case pause_epoch <= now
        subprocess.run([str(SCRIPT_PATH)], capture_output=True)

    return get_schedule_status()


def cancel_schedule() -> dict[str, Any]:
    if platform.system().lower() == "darwin":
        uid = os.getuid()
        subprocess.run(["launchctl", "bootout", f"gui/{uid}/{PLIST_LABEL}"], capture_output=True)
    if PLIST_PATH.exists():
        PLIST_PATH.unlink()
    if FLAG_PATH.exists():
        FLAG_PATH.unlink()
    return {"ok": True, "cancelled": True}
